local A=require('trajectory_animation')
local state={}
local first=A.frame(state,1,0,false)
assert(first.Reveal==0 and first.DrawStrength==0 and first.ContactPulse==0)
local half=A.frame(state,1.06,.5,true)
assert(math.abs(half.Reveal-.5)<1e-8 and half.DrawStrength==.5 and half.ContactPulse==1)
local full=A.frame(state,1.12,1,true)
assert(math.abs(full.Reveal-1)<1e-8 and full.ContactPulse<1)
local later=A.frame(state,2,1,false)
assert(later.Reveal==1 and later.ContactPulse==0)
assert(A.frame(state,2.1,1,true).ContactPulse==1)
assert(A.frame(state,0,3,false).Reveal==0,'time reset must restart appearance')
assert(A.frame({},4,-1,false).DrawStrength==0)
assert(not pcall(A.frame,{},0/0,1,false))
print('PASS trajectory appearance timing, draw strength, contact pulse and time reset')
